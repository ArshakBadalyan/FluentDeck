function topicStarterPrompt(title) {
  return `Let's talk about ${title.toLowerCase()}. Share your thoughts, experiences, and opinions — I'll help you practice natural English.`;
}

function buildTopics(titles, levelGroup) {
  const icons = TOPIC_ICON_KEYS[levelGroup];
  return titles.map((title, index) =>
    topic(
      title,
      levelGroup,
      icons[index % icons.length],
      index + 1,
      topicStarterPrompt(title),
    ),
  );
}

